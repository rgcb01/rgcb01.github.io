// Published numbers for Lab 003 (video, cards, posts, challenge reference) must be what the model computes.
// `node scripts/labs/check-sraf-published.mjs --write` regenerates; without --write it verifies, including the
// numbers embedded in the committed explainer.
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { SRAF_DESIGNS, SRAF_NUMERICS, srafAnalyze, srafCd, srafDenseMask, srafImage, srafMask, srafNormalize, srafThresholdForCd } from '../../src/labs/sub-resolution-assist-features/model.js';

const FILE = 'src/labs/sub-resolution-assist-features/published.json';
const r1 = (v) => Math.round(v * 10) / 10, r3 = (v) => Math.round(v * 1000) / 1000;
const summary = (a) => ({
  dofCdOnly: Math.round(a.windows.cdOnly.dof), dofDefectFree: Math.round(a.windows.defectFree.dof), dofSafe: Math.round(a.windows.safe.dof),
  verdict: a.verdict, marginInCdWindow: a.marginCdWindow == null ? null : r3(a.marginCdWindow), doseToSize: r3(a.E0),
  nilsAerial: r3(a.nilsAerial), nilsResist: r3(a.nilsResist), elBestFocus: r3(a.elBestFocus),
});
const designs = {
  none: summary(srafAnalyze(SRAF_DESIGNS.none)), recommended: summary(srafAnalyze(SRAF_DESIGNS.recommended)),
  twoBy40: summary(srafAnalyze({ bars: 2, barWidth: 40 })), oversized: summary(srafAnalyze(SRAF_DESIGNS.oversized)),
  dense200: summary(srafAnalyze({}, { mask: srafDenseMask(90, 200) })),
};
const conventional = { none: summary(srafAnalyze({ illumination: 'conventional', sigmaOut: 0.6, bars: 0 })), recommended: summary(srafAnalyze({ illumination: 'conventional', sigmaOut: 0.6, ...SRAF_DESIGNS.recommended })) };
// shared dose: the dense lines' dose-to-size applied to the isolated line, with and without assists
const P = srafNormalize({}), tDense = srafThresholdForCd(srafImage(srafDenseMask(P.cd, 200).all, P, 0), P.cd);
const sharedDose = { dose: r3(1 / tDense), isoCd: r1(srafCd(srafImage(srafMask(srafNormalize(SRAF_DESIGNS.none)).all, P, 0), tDense)), isoWithRecommendedCd: r1(srafCd(srafImage(srafMask(srafNormalize(SRAF_DESIGNS.recommended)).all, P, 0), tDense)), target: P.cd };
// challenge reference: best SAFE design on a coarse grid (the viewer can search between grid points)
const grid = []; for (const bars of [1, 2, 3]) for (const barWidth of [20, 30, 40, 50]) for (const barSpace of [80, 110, 140]) grid.push({ bars, barWidth, barSpace, barPitch: 200 });
const scored = grid.map(d => ({ d, a: srafAnalyze(d) })).map(({ d, a }) => ({ ...d, safe: Math.round(a.windows.safe.dof), cdOnly: Math.round(a.windows.cdOnly.dof), verdict: a.verdict }));
const bestSafe = scored.filter(s => s.verdict === 'safe').sort((a, b) => b.safe - a.safe)[0], bestCdOnly = [...scored].sort((a, b) => b.cdOnly - a.cdOnly)[0];
const data = {
  note: 'Generated by scripts/labs/check-sraf-published.mjs from model.js. Do not edit by hand. DOF values carry about +-1 nm numerical uncertainty (see the convergence checks).',
  optics: { wavelength: P.wavelength, na: P.na, illumination: P.illumination, sigmaIn: P.sigmaIn, sigmaOut: P.sigmaOut },
  criteria: { cd: P.cd, cdTolerance: P.cdTolerance, exposureLatitude: P.el, safeMargin: P.safeMargin, blur: P.blur },
  numerics: { sourcePoints: SRAF_NUMERICS.sourcePoints, grid: SRAF_NUMERICS.grid, field: SRAF_NUMERICS.field, focusStep: SRAF_NUMERICS.focusStep },
  designs, conventional, sharedDose,
  challenge: { gridDesigns: grid.length, bestSafe, bestCdOnlyIgnoringDefects: bestCdOnly },
};
if (process.argv.includes('--write')) { writeFileSync(FILE, JSON.stringify(data, null, 2) + '\n'); console.log(`wrote ${FILE}`); }
else {
  assert(existsSync(FILE), `${FILE} missing: run with --write`);
  assert.deepEqual({ ...JSON.parse(readFileSync(FILE, 'utf8')), note: data.note }, data, 'published.json no longer matches the model: rerun with --write and re-render the assets');
  const EXP = 'public/assets/labs/sub-resolution-assist-features/explainer.html';
  if (existsSync(EXP)) {
    const html = readFileSync(EXP, 'utf8'), at = html.indexOf('const SRFD = '), d = JSON.parse(html.slice(at + 13, html.indexOf(';\n', at)));
    for (const k of ['none', 'recommended', 'oversized', 'dense200']) assert.deepEqual(d.summary[k], designs[k], `explainer summary ${k} differs: rebuild it (npm run labs:explainer -- sub-resolution-assist-features build)`);
  }
  console.log('SRAF published numbers match the model and the committed explainer.');
}
