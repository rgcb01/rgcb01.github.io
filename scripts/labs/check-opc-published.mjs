// Published numbers for Lab 002 (used by the video, the cards and the post drafts) must be what the model
// computes. `node scripts/labs/check-opc-published.mjs --write` regenerates the file; without --write it verifies.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { opcExperiment, opcAerialImage, opcFragmentMask, opcMetrics, opcRuleMask, opcSites, OPC_NUMERICS } from '../../src/labs/optical-proximity-correction/model.js';

const FILE = 'src/labs/optical-proximity-correction/published.json';
const r2 = (v) => Math.round(v * 100) / 100;
const pickM = (m) => ({ rmsEpe: r2(m.rms), maxAbsEpe: r2(m.maxAbs), withinTolerance: r2(m.within), lineEndTip: r2(m.lineEnd), outerCorner: r2(m.outerCorner), lineEndCorners: r2(m.endCorner), innerCorner: r2(m.innerCorner), isoCdError: r2(m.isoCdError), denseCdError: r2(m.denseCdError), sites: m.n, pinched: m.pinched, bridged: m.bridged });

const r = opcExperiment({}), sites = opcSites(r.polys, r.params.cd);
const sweep = [0, 0.25, 0.5, 0.75, 1].map(g => ({ strength: g, ...pickM(opcMetrics(opcAerialImage(opcFragmentMask(r.polys, r.model.frags, g), r.params), sites, r.thr)) }));
const frag = (kind, poly) => r.model.frags.filter(f => f.kind === kind && (!poly || f.poly === poly)).map(f => f.d);
const pitch = [90, 80].map(cd => { const e = opcExperiment({ cd, space: cd }); return { cd, k1: r2(cd * r.params.na / r.params.wavelength), rmsBefore: r2(e.before.rms), rmsAfter: r2(e.after.rms), loopConverged: !e.model.diverged, pinchedOrBridged: e.after.pinched + e.after.bridged }; });
// best rule-based mask on a coarse grid (the challenge's reference point): 288 combinations of the five rules
const grid = []; for (const bias of [-4, -2, 0, 2]) for (const serif of [0, 30, 50]) for (const hammerOverhang of [0, 10, 20]) for (const hammerLength of [20, 40]) for (const hammerExtension of [0, 5, 10, 15]) grid.push({ bias, serif, hammerOverhang, hammerLength, hammerExtension });
const scored = grid.map(rules => ({ rules, m: opcMetrics(opcAerialImage(opcRuleMask(r.polys, r.params.cd, rules), r.params), sites, r.thr) })).sort((a, b) => a.m.rms - b.m.rms);
const ruleSearch = { combinations: grid.length, best: { ...scored[0].rules, ...pickM(scored[0].m) } };
const data = {
  note: 'Generated by scripts/labs/check-opc-published.mjs from model.js. Do not edit by hand.',
  optics: { wavelength: r.params.wavelength, na: r.params.na, sigma: r.params.sigma, k1: r2(r.params.cd * r.params.na / r.params.wavelength) },
  layout: { cd: r.params.cd, space: r.params.space },
  resist: { threshold: Math.round(r.thr * 10000) / 10000, blur: r.params.blur, polarity: 'positive tone, bright-field binary mask: printed feature where blurred intensity < threshold' },
  numerics: { sourcePoints: OPC_NUMERICS.sourcePoints, iterations: OPC_NUMERICS.opcIterations, gain: OPC_NUMERICS.opcGain, toleranceNm: OPC_NUMERICS.epeTolerance },
  uncorrected: pickM(r.before), modelBased: pickM(r.after),
  emergent: {
    lineEndSideCornerOffsetMax: r2(Math.max(...frag('corner', 'iso'))), lineEndTipOffset: r2(frag('lineEnd', 'iso')[0]),
    isoMidEdgeOffset: r2(frag('edge', 'iso').reduce((a, b) => a + b, 0) / frag('edge', 'iso').length),
    elbowCornerOffsets: frag('corner', 'elbow').map(r2),
  },
  strengthSweep: sweep, pitchStudy: pitch, ruleSearch,
};
if (process.argv.includes('--write')) { writeFileSync(FILE, JSON.stringify(data, null, 2) + '\n'); console.log(`wrote ${FILE}`); }
else {
  assert(existsSync(FILE), `${FILE} missing: run with --write`);
  const saved = JSON.parse(readFileSync(FILE, 'utf8'));
  assert.deepEqual({ ...saved, note: data.note }, data, 'published.json no longer matches the model: rerun with --write and re-render the assets');
  // the committed explainer must carry the same numbers (it embeds the model states it was built from)
  const EXP = 'public/assets/labs/optical-proximity-correction/explainer.html';
  if (existsSync(EXP)) {
    const html = readFileSync(EXP, 'utf8'), at = html.indexOf('const OPCD = '), json = html.slice(at + 13, html.indexOf(';\n', at));
    const st = JSON.parse(json).states, a = st[0].metrics, b = st[st.length - 1].metrics;
    for (const [m, ref] of [[a, data.uncorrected], [b, data.modelBased]]) for (const [k, key] of [['rms', 'rmsEpe'], ['lineEnd', 'lineEndTip'], ['outerCorner', 'outerCorner'], ['within', 'withinTolerance']])
      assert(Math.abs(r2(m[k]) - ref[key]) < 0.011, `explainer ${k} ${r2(m[k])} differs from published ${ref[key]}: rebuild it (npm run labs:explainer -- optical-proximity-correction build)`);
  }
  console.log('OPC published numbers match the model and the committed explainer.');
}
