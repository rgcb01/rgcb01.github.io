// Build step for the Lab 003 explainer (run by scripts/labs/simulab.mjs): runs model.js and writes data.gen.js.
// States: the isolated 90 nm line with two assist bars per side (110 nm from the line, 200 nm bar pitch) whose
// width goes 0, 5, ... 60 nm (0 = no assists), plus dense 90 nm lines at 200 nm pitch for comparison. Each state
// carries the full analysis (focus scan, three DOF windows, verdict, margin) and the blurred intensity sampled
// through focus as a terrain. A frame-exact video cannot afford a 1 s analysis per frame, so the explainer reads
// these exact states and interpolates only the drawing between neighbouring 5 nm steps while a width animates;
// every number on screen is the exact state at the nearest step. `summary` is checked by check-sraf-published.mjs.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SRAF_DESIGNS, srafAnalyze, srafAt, srafDenseMask, srafImage, srafMask, srafNormalize, srafSpectrum } from '../model.js';

const WIDTHS = [0, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55, 60];
const XS = 450, DX = 7.5, ZS = 400, DZ = 20;    // terrain: position -450..450 nm, focus -400..400 nm
const r3 = (v) => Math.round(v * 1000) / 1000, r1 = (v) => Math.round(v * 10) / 10;
const u8 = (arr) => Buffer.from(Uint8Array.from(arr)).toString('base64');
const win = (w) => ({ dof: r1(w.dof), z0: r1(w.z0 ?? 0), z1: r1(w.z1 ?? 0), e0: r3(w.e0 ?? 0), e1: r3(w.e1 ?? 0) });
const summary = (a) => ({
  dofCdOnly: Math.round(a.windows.cdOnly.dof), dofDefectFree: Math.round(a.windows.defectFree.dof), dofSafe: Math.round(a.windows.safe.dof),
  verdict: a.verdict, marginInCdWindow: a.marginCdWindow == null ? null : r3(a.marginCdWindow), doseToSize: r3(a.E0),
  nilsAerial: r3(a.nilsAerial), nilsResist: r3(a.nilsResist), elBestFocus: r3(a.elBestFocus),
});
function pack(a, terrain) {
  return {
    bars: a.mask.bars.map(([x0, x1]) => [r1(x0), r1(x1)]), t0: r3(a.t0), E0: r3(a.E0), verdict: a.verdict,
    margin: a.marginCdWindow == null ? null : r3(a.marginCdWindow),
    windows: { cdOnly: win(a.windows.cdOnly), defectFree: win(a.windows.defectFree), safe: win(a.windows.safe) },
    rows: a.rows.map(r => [r.z, r.ok ? 1 : 0, r3(r.Elo), r3(r.Ehi), r3(r.Eprint)]),
    terrain,
  };
}

export default function prepare({ stageDir }) {
  const t0 = Date.now(), P = srafNormalize({}), nx = 2 * XS / DX + 1, nz = 2 * ZS / DZ + 1, states = [];
  for (const w of WIDTHS) {
    const d = w ? { bars: 2, barWidth: w, barSpace: 110, barPitch: 200 } : { bars: 0 }, a = srafAnalyze(d), m = srafMask(a.params);
    const half = [];                                // I(x, z) = I(x, -z) exactly (checked in check-sraf-model.mjs)
    for (let j = 0; j <= ZS / DZ; j++) { const img = srafImage(m.all, a.params, j * DZ); half.push(Array.from({ length: nx }, (_, i) => srafAt(img, -XS + i * DX))); }
    const terrain = [];
    for (let j = 0; j < nz; j++) terrain.push(...half[Math.abs(j - ZS / DZ)].map(v => Math.max(0, Math.min(255, Math.round(v / 1.3 * 255)))));
    states.push({ w, ...pack(a, u8(terrain)) });
  }
  const dense = srafAnalyze({}, { mask: srafDenseMask(P.cd, 200) });
  const F = Array.from({ length: 161 }, (_, i) => -2 + i * 0.025), fu = P.na / P.wavelength;
  const spec = (d) => { const m = srafMask(srafNormalize(d)); return F.map(f => r3(srafSpectrum(m.all, f * fu))); };
  const data = {
    generated: 'scripts/labs/simulab.mjs -> src/labs/sub-resolution-assist-features/simulab/prepare.mjs (model.js)',
    params: { wavelength: P.wavelength, na: P.na, sigmaIn: P.sigmaIn, sigmaOut: P.sigmaOut, cd: P.cd, blur: P.blur, cdTolerance: P.cdTolerance, el: P.el, safeMargin: P.safeMargin },
    terrain: { nx, nz, xs: XS, zs: ZS, scale: 1.3 }, widths: WIDTHS, states,
    dense: { windows: { cdOnly: win(dense.windows.cdOnly) }, rows: dense.rows.map(r => [r.z, r.ok ? 1 : 0, r3(r.Elo), r3(r.Ehi), 0]) },
    spectrum: { f: F, none: spec(SRAF_DESIGNS.none), recommended: spec(SRAF_DESIGNS.recommended) },
    summary: { none: summary(srafAnalyze(SRAF_DESIGNS.none)), recommended: summary(srafAnalyze(SRAF_DESIGNS.recommended)), oversized: summary(srafAnalyze(SRAF_DESIGNS.oversized)), dense200: summary(dense) },
  };
  writeFileSync(join(stageDir, 'data.gen.js'), `// GENERATED by prepare.mjs from model.js. Do not edit.\nconst SRFD = ${JSON.stringify(data)};\n`);
  const s = (w) => states.find(x => x.w === w).windows.defectFree.dof;
  console.log(`prepare: ${(JSON.stringify(data).length / 1024).toFixed(0)} KB, ${states.length} states in ${((Date.now() - t0) / 1000).toFixed(1)} s; defect-free DOF ${s(0)} / ${s(30)} / ${s(60)} nm`);
}
